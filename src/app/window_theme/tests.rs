#[test]
fn css_reader_follows_imports_uses_later_rules_and_survives_odd_input() {
    let (fx, env) = Fixture::new(true);
    for n in ["a", "b", "c", "d"] {
        fx.png(&format!("home/.config/gtk-3.0/{n}.png"), [9, 9, 9, 255], 4);
    }
    fx.write(
        "home/.config/gtk-3.0/gtk.css",
        "@define-color fg #fff;\n@import 'window_decorations.css';\n@import url(\"gtk.css\");\n\
         @media (min-width: 1px) { .titlebar button.close { background-image: url(a.png) } }\n\
         .titlebar button.minimize { background-image: image(url(\"b.png\"), linear-gradient(red, blue)); }\n\
         /* .titlebar button.maximize { background-image: url(a.png) } */\n\
         .titlebar button.maximize { background: url(\"c.png\") no-repeat center; border: 1px solid }\n\
         .titlebar button.maximize { -gtk-icon-source: none; }\n",
    );
    fx.write(
        "home/.config/gtk-3.0/window_decorations.css",
        "@import url(\"../outside.css\");\n.titlebar button.close { background-image: url(d.png) }\n\
         .titlebar button.close { background-image: url(missing.png) }\n",
    );
    let resolved = resolve_env(&env).unwrap();
    let p = |kind| path_of(&resolved, kind, State::Normal, &fx);
    // The unreadable import and the missing file are skipped; `d.png` stays.
    assert!(p(Kind::Close).ends_with("d.png"));
    assert!(p(Kind::Minimize).ends_with("b.png"));
    assert!(p(Kind::Maximize).ends_with("c.png"));
}

