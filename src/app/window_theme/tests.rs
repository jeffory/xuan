fn path_of(resolved: &Resolved, kind: Kind, state: State, fx: &Fixture) -> String {
    resolved
        .path(kind, state)
        .map(|p| {
            p.strip_prefix(fx.dir.path())
                .unwrap()
                .to_string_lossy()
                .into_owned()
        })
        .unwrap_or_default()
}

fn resolve_env(env: &Env) -> Option<Resolved> {
    resolve(env, &Probe::new(env))
}

#[test]
fn kde_gtk_config_css_resolves_every_button_and_state() {
    let (fx, env) = Fixture::new(true);
    kde_gtk_config(&fx, "gtk-3.0");
    fx.write(
        "home/.config/kdeglobals",
        "[Colors:Header]\r\nForegroundNormal=252,252,252\r\nForegroundInactive=161,169,177\r\n",
    );
    let resolved = resolve_env(&env).expect("kde-gtk-config assets");
    assert_eq!(resolved.source, Source::KdeGtkConfig);
    let p = |kind, state| path_of(&resolved, kind, state, &fx);
    let dir = "home/.config/gtk-3.0/assets/titlebutton-";
    assert_eq!(p(Kind::Close, State::Normal), format!("{dir}close.png"));
    assert_eq!(
        p(Kind::Close, State::Hover),
        format!("{dir}close-hover.png")
    );
    assert_eq!(
        p(Kind::Close, State::Active),
        format!("{dir}close-active.png")
    );
    assert_eq!(
        p(Kind::Close, State::Backdrop),
        format!("{dir}close-backdrop.png")
    );
    assert_eq!(
        p(Kind::Minimize, State::Normal),
        format!("{dir}minimize.png")
    );
    assert_eq!(
        p(Kind::Minimize, State::Hover),
        format!("{dir}minimize-hover.png")
    );
    assert_eq!(
        p(Kind::Maximize, State::Normal),
        format!("{dir}maximize.png")
    );
    assert_eq!(
        p(Kind::Maximize, State::Hover),
        format!("{dir}maximize-hover.png")
    );
    assert_eq!(p(Kind::Restore, State::Normal), format!("{dir}restore.png"));
    assert_eq!(
        p(Kind::Restore, State::Hover),
        format!("{dir}restore-hover.png")
    );
    assert_eq!(p(Kind::Minimize, State::Active), "");

    // `-gtk-scaled` offers the 2x image on a HiDPI display.
    let at = |ppp| {
        resolved
            .pick(Kind::Close, State::Normal, ppp)
            .unwrap()
            .asset
            .clone()
    };
    assert!(at(1.0).path.ends_with("titlebutton-close.png") && at(1.0).scale == 1);
    assert!(at(2.0).path.ends_with("titlebutton-close@2.png") && at(2.0).scale == 2);
    assert!(at(1.5).path.ends_with("titlebutton-close@2.png"));
    assert_eq!(
        resolved.tints,
        Tints {
            active: Some([252, 252, 252]),
            inactive: Some([161, 169, 177]),
            ..Tints::default()
        }
    );
}

#[test]
fn missing_states_fall_back_to_the_normal_image_with_a_highlight() {
    let (fx, env) = Fixture::new(true);
    kde_gtk_config(&fx, "gtk-3.0");
    let resolved = resolve_env(&env).unwrap();
    // Own image: no highlight.
    let hover = resolved.pick(Kind::Close, State::Hover, 1.0).unwrap();
    assert!(hover.asset.path.ends_with("titlebutton-close-hover.png"));
    assert_eq!(hover.highlight, Highlight::None);
    // Minimize has no pressed image: the hover one, highlighted.
    let pressed = resolved.pick(Kind::Minimize, State::Active, 1.0).unwrap();
    assert!(
        pressed
            .asset
            .path
            .ends_with("titlebutton-minimize-hover.png")
    );
    assert_eq!(pressed.highlight, Highlight::Pressed);
    // Maximize has no backdrop image: the normal one, dimmed.
    let backdrop = resolved.pick(Kind::Maximize, State::Backdrop, 1.0).unwrap();
    assert!(backdrop.asset.path.ends_with("titlebutton-maximize.png") && backdrop.dim);
    // A theme with no hover image at all.
    let (fx2, env2) = Fixture::new(true);
    fx2.png("home/.config/gtk-3.0/a.png", [0; 4], 4);
    fx2.write(
        "home/.config/gtk-3.0/window_decorations.css",
        ".titlebar button.close, .titlebar button.minimize, .titlebar button.maximize { background-image: url(a.png) }",
    );
    let plain = resolve_env(&env2).unwrap();
    let hover = plain.pick(Kind::Close, State::Hover, 1.0).unwrap();
    assert!(hover.asset.path.ends_with("a.png") && hover.highlight == Highlight::Hover);
    // No restore image: the caller draws its own glyph for it.
    assert!(plain.pick(Kind::Restore, State::Normal, 1.0).is_none());
}

