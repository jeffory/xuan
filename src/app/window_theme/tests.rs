#[test]
fn icon_theme_lookup_follows_inherits_picks_the_nearest_size_and_falls_back_to_hicolor() {
    let (fx, mut env) = Fixture::new(true);
    fx.write(
        "home/.config/kdeglobals",
        "[Icons]\nTheme=Child\n[Colors:Header]\nForegroundNormal=#fcfcfc\n[WM]\nactiveForeground=1,2,3\n",
    );
    icon_theme(
        &fx,
        "Child",
        "[Icon Theme]\r\nName=Child\r\nInherits=Parent,Other\r\nDirectories=actions/16,actions/48\r\n\
         [actions/16]\nSize=16\nType=Fixed\n[actions/48]\nSize=48\nType=Fixed\n",
    );
    icon_theme(
        &fx,
        "Parent",
        "[Icon Theme]\nInherits=\nDirectories=actions/scalable,actions/22\n\
         [actions/scalable]\nSize=16\nMinSize=8\nMaxSize=512\nType=Scalable\n\
         [actions/22]\nSize=22\nType=Fixed\n",
    );
    icon_theme(
        &fx,
        "hicolor",
        "[Icon Theme]\nDirectories=actions/16\n[actions/16]\nSize=16\nType=Fixed\n",
    );
    // Child has the close and minimize icons at two sizes: the 16 px one wins.
    for name in ["window-close-symbolic", "window-minimize-symbolic"] {
        fx.svg(
            &format!("usr/share/icons/Child/actions/16/{name}.svg"),
            "#232629",
        );
        fx.svg(
            &format!("usr/share/icons/Child/actions/48/{name}.svg"),
            "#232629",
        );
    }
    // Parent has maximize at 22 and a scalable one: scalable (distance 0) wins.
    fx.svg(
        "usr/share/icons/Parent/actions/22/window-maximize-symbolic.svg",
        "#232629",
    );
    fx.svg(
        "usr/share/icons/Parent/actions/scalable/window-maximize-symbolic.svg",
        "#232629",
    );
    // Restore only exists in hicolor.
    fx.svg(
        "usr/share/icons/hicolor/actions/16/window-restore-symbolic.svg",
        "#232629",
    );
    let resolved = resolve_env(&env).unwrap();
    assert_eq!(resolved.source, Source::IconTheme);
    let p = |kind| path_of(&resolved, kind, State::Normal, &fx);
    assert_eq!(
        p(Kind::Close),
        "usr/share/icons/Child/actions/16/window-close-symbolic.svg"
    );
    assert_eq!(
        p(Kind::Minimize),
        "usr/share/icons/Child/actions/16/window-minimize-symbolic.svg"
    );
    assert_eq!(
        p(Kind::Maximize),
        "usr/share/icons/Parent/actions/scalable/window-maximize-symbolic.svg"
    );
    assert_eq!(
        p(Kind::Restore),
        "usr/share/icons/hicolor/actions/16/window-restore-symbolic.svg"
    );
    assert!(
        resolved
            .pick(Kind::Close, State::Normal, 1.0)
            .unwrap()
            .asset
            .symbolic
    );
    // Header colours win over [WM].
    assert_eq!(resolved.tints.active, Some([252, 252, 252]));

    // GTK desktops name the icon theme in settings.ini, then gsettings.
    env.kde = false;
    fx.write(
        "home/.config/gtk-3.0/settings.ini",
        "[Settings]\ngtk-icon-theme-name=Parent\n",
    );
    let resolved = resolve_env(&env);
    assert!(
        resolved.is_none(),
        "Parent lacks close and minimize: {resolved:?}"
    );
    fx.write(
        "home/.config/gtk-3.0/settings.ini",
        "[Settings]\ngtk-icon-theme-name=Child\n",
    );
    assert!(resolve_env(&env).is_some());
}

