use std::{fs, path::Path, time::Duration};

use super::*;

/// A fake home directory with the XDG layout the lookup reads.
pub(in crate::app) struct Fixture {
    pub dir: tempfile::TempDir,
}

impl Fixture {
    pub fn new(kde: bool) -> (Self, Env) {
        let dir = tempfile::tempdir().unwrap();
        let fixture = Self { dir };
        let env = fixture.env(kde);
        (fixture, env)
    }

    /// A fresh environment over this fixture's folders.
    pub fn env(&self, kde: bool) -> Env {
        let home = self.dir.path().join("home");
        Env {
            config_home: home.join(".config"),
            data_home: home.join(".local/share"),
            data_dirs: vec![self.dir.path().join("usr/share")],
            home,
            kde,
            ..Env::default()
        }
    }

    pub fn write(&self, relative: &str, content: impl AsRef<[u8]>) {
        let path = self.dir.path().join(relative);
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(path, content).unwrap();
    }

    pub fn path(&self, relative: &str) -> PathBuf {
        self.dir.path().join(relative)
    }

    /// A valid PNG of one colour.
    pub fn png(&self, relative: &str, rgba: [u8; 4], size: u32) {
        let path = self.path(relative);
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        image::RgbaImage::from_pixel(size, size, image::Rgba(rgba))
            .save(path)
            .unwrap();
    }

    pub fn svg(&self, relative: &str, fill: &str) {
        self.write(
            relative,
            format!(
                r#"<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 16 16"><rect width="16" height="16" fill="{fill}"/></svg>"#
            ),
        );
    }
}

